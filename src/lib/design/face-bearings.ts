/**
 * Hung bearings (docs/redesign/BENTO_TYPE.md, "Hung bearings"). A glyph's ink
 * starts in from its origin by its left side bearing, a share of the em, so
 * text set large inks visibly inside the edge its box sits on. A display text
 * that starts on an edge hangs its first glyph's bearing outside it.
 * `npm run type:bearings` measures the display face's bearings from rendered
 * ink and writes face-bearings.gen.ts; the e2e check measures the page again.
 */

import { DISPLAY_BEARINGS } from './face-bearings.gen'

export const FACE_BEARINGS_PATH = 'src/lib/design/face-bearings.gen.ts'

/** The glyphs the table holds: a display text starts with one of them. */
export const BEARING_GLYPHS = Object.freeze([...'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'])
export const TABULAR_GLYPHS = Object.freeze([...'0123456789'])

/** Figures set proportional, or tabular (`font-variant-numeric: tabular-nums`), which pads each digit to one width. */
export type Figures = 'proportional' | 'tabular'

export interface Bearings {
  /** The weight the display face is set in wherever it hangs. */
  readonly weight: number
  readonly proportional: Readonly<Record<string, number>>
  readonly tabular: Readonly<Record<string, number>>
}

const median = (values: readonly number[]): number => [...values].sort((a, b) => a - b)[Math.floor(values.length / 2)]

/** The face's median bearing: it stands for a first glyph the table does not hold. */
export const MEDIAN_BEARING = median(Object.values(DISPLAY_BEARINGS.proportional))

/** How far, in em, a display text hangs outside its edge: its first glyph's bearing. */
export function hangOf(text: string, figures: Figures = 'proportional', table: Bearings = DISPLAY_BEARINGS): number {
  const glyph = text.trimStart().charAt(0)
  return (figures === 'tabular' ? table.tabular[glyph] : undefined) ?? table.proportional[glyph] ?? MEDIAN_BEARING
}

const round = (n: number): number => Math.round(n * 10_000) / 10_000

/** The generated module for a table read at `measuredAt` px. */
export const bearingsModule = (table: Bearings, measuredAt: number): string => {
  const entries = (record: Readonly<Record<string, number>>): string =>
    Object.entries(record)
      .map(([glyph, bearing]) => `    ${JSON.stringify(glyph)}: ${round(bearing)},`)
      .join('\n')
  return `// Generated by \`npm run type:bearings\` (src/lib/design/face-bearings.ts). Do not edit.
import type { Bearings } from './face-bearings'

/** The display face's left side bearings, in em, read from rendered ink at ${measuredAt} px. */
export const DISPLAY_BEARINGS: Bearings = {
  weight: ${table.weight},
  proportional: {
${entries(table.proportional)}
  },
  tabular: {
${entries(table.tabular)}
  },
}
`
}
