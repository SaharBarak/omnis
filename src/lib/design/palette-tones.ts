import { LAYERS, PALETTES, THEMES, layerProblem, type PaletteTones } from './bento-palette'
import { solveCategorical } from './categorical'

/** Where `npm run palette:tones` writes the solved table. */
export const PALETTE_TONES_PATH = 'src/lib/design/palette-tones.gen.ts'

/** Solves every palette's layer lightness, per theme (BENTO_COLOR.md "Layers"). */
export const solvePaletteTones = (): PaletteTones =>
  Object.fromEntries(PALETTES.map((spec) => [spec.id, Object.fromEntries(THEMES.map((theme) => [theme, solveCategorical(layerProblem(spec, theme))]))])) as PaletteTones

/** The generated module's source, ordered as the palette declares its themes and layers. */
export function tonesModule(tones: PaletteTones): string {
  const theme = (values: Readonly<Record<string, number>>): string => `{ ${LAYERS.map((layer) => `${layer}: ${values[layer]}`).join(', ')} }`
  const palettes = Object.entries(tones).map(([id, themes]) => `  ${id}: {\n${THEMES.map((t) => `    ${t}: ${theme(themes[t])},`).join('\n')}\n  },`)
  return [
    '// Generated by `npm run palette:tones` (src/lib/design/palette-tones.ts). Do not edit.',
    "import type { PaletteTones } from './bento-palette'",
    '',
    'export const PALETTE_TONES: PaletteTones = {',
    ...palettes,
    '}',
    '',
  ].join('\n')
}
