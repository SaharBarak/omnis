/**
 * The mobile app's Lantern tokens, generated from the web's one source of
 * truth (docs/redesign/MOBILE_V2_MATCH.md). The web resolves the Lantern
 * palette (src/lib/design/bento-palette.ts) through the OKLCH solver and emits
 * hex; React Native takes the same hex, so mobile and web render the exact same
 * colours. The radius scale comes across unchanged. A palette change on the web
 * regenerates mobile too:
 *
 *   npm run gen:mobile-theme
 *
 * Only the palette and radius are generated here — the type scale is resolved
 * per component during the migration, where mobile picks its own fixed sizes.
 */

import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { resolvePalette } from '../../src/lib/design/bento-palette'
import { paletteSpec, ROLES, THEMES, type Role, type Swatch } from '../../src/lib/design/palette-spec'
import { DEFAULT_PALETTE } from '../../src/lib/design/palette-ids'
import { toHex } from '../../src/lib/design/color'
import { RADII } from '../../src/lib/design/radius'

/** A role's colour as RN takes it: six-digit hex, or eight digits when it carries alpha. */
const hexOf = ({ oklch, alpha }: Swatch): string =>
  alpha >= 1 ? toHex(oklch) : `${toHex(oklch)}${Math.round(alpha * 255).toString(16).padStart(2, '0')}`

const spec = paletteSpec(DEFAULT_PALETTE)

const palette = Object.fromEntries(
  THEMES.map((theme) => {
    const resolved = resolvePalette(spec, theme)
    return [theme, Object.fromEntries(ROLES.map((role) => [role, hexOf(resolved[role])]))]
  })
)

const file = `/**
 * GENERATED by scripts/design/gen-mobile-theme.ts — do not edit by hand.
 * The web's Lantern palette (src/lib/design/bento-palette.ts) resolved to hex,
 * plus the shared radius scale. Dark is the default; the inverse section uses
 * the opposite theme. Run \`npm run gen:mobile-theme\` after a palette change.
 */

export const LANTERN = ${JSON.stringify(palette, null, 2)} as const

export type LanternTheme = keyof typeof LANTERN
export type LanternRole = keyof (typeof LANTERN)['dark']

/** The opposite theme, for an inverse section (BENTO_COLOR.md "Inverse sections"). */
export const otherTheme = (theme: LanternTheme): LanternTheme => (theme === 'dark' ? 'light' : 'dark')

export const RADIUS = ${JSON.stringify(RADII, null, 2)} as const

export type RadiusRole = keyof typeof RADIUS
`

const tokensOut = join(process.cwd(), 'packages/mobile/src/theme/bento-tokens.ts')
writeFileSync(tokensOut, file)
process.stdout.write(`wrote ${tokensOut}\n`)

/**
 * The Material 3 role set, sourced from Lantern so every existing screen and M3
 * component renders the web's palette while components migrate onto useLantern()
 * (docs/redesign/MOBILE_V2_MATCH.md). The map is bento: cool dark surfaces, gold
 * action as `primary`, cyan accent as `secondary`, neutral chips with accent
 * text instead of tonal containers, coral `danger` as error. `shadow`/`scrim`
 * stay solid black (RN shadow colour).
 */
const M3_FROM_LANTERN: Readonly<Record<string, Role | '#000000'>> = {
  background: 'ground', onBackground: 'ink',
  surface: 'ground', surfaceDim: 'ground', surfaceBright: 'surface2',
  surfaceContainerLowest: 'art', surfaceContainerLow: 'surface1', surfaceContainer: 'surface1',
  surfaceContainerHigh: 'surface2', surfaceContainerHighest: 'chip',
  onSurface: 'ink', surfaceVariant: 'chip', onSurfaceVariant: 'ink2',
  inverseSurface: 'ink', inverseOnSurface: 'ground',
  outline: 'line', outlineVariant: 'line',
  shadow: '#000000', scrim: '#000000', surfaceTint: 'accent',
  primary: 'action', onPrimary: 'onAction', primaryContainer: 'chip', onPrimaryContainer: 'action', inversePrimary: 'action',
  secondary: 'accent', onSecondary: 'onAccent', secondaryContainer: 'chip', onSecondaryContainer: 'accent',
  tertiary: 'accentSoft', onTertiary: 'onAccent', tertiaryContainer: 'chip', onTertiaryContainer: 'ink2',
  error: 'danger', onError: 'art', errorContainer: 'chip', onErrorContainer: 'danger',
  primaryFixed: 'chip', primaryFixedDim: 'surface2', onPrimaryFixed: 'ink', onPrimaryFixedVariant: 'ink2',
  secondaryFixed: 'chip', secondaryFixedDim: 'surface2', onSecondaryFixed: 'ink', onSecondaryFixedVariant: 'ink2',
  tertiaryFixed: 'chip', tertiaryFixedDim: 'surface2', onTertiaryFixed: 'ink', onTertiaryFixedVariant: 'ink2',
}

const M3_ROLES = Object.keys(M3_FROM_LANTERN)

const m3Scheme = (theme: (typeof THEMES)[number]): Record<string, string> => {
  const resolved = resolvePalette(spec, theme)
  return Object.fromEntries(
    M3_ROLES.map((m3) => {
      const source = M3_FROM_LANTERN[m3]
      return [m3, source === '#000000' ? '#000000' : hexOf(resolved[source])]
    })
  )
}

const m3Body = (name: string, theme: (typeof THEMES)[number]) =>
  `export const ${name}: M3ColorScheme = ${JSON.stringify(m3Scheme(theme), null, 2)}\n`

const m3File = `/**
 * GENERATED by scripts/design/gen-mobile-theme.ts — do not edit by hand.
 * The Material 3 role set sourced from the web's Lantern palette, so every
 * screen and M3 component renders the pleiad.io colours. Run
 * \`npm run gen:mobile-theme\` after a palette change. The role-to-Lantern map
 * lives in the generator.
 */

/** The 49 M3 roles. Every colour an M3 component reads is one of these. */
export interface M3ColorScheme {
${M3_ROLES.map((r) => `  ${r}: string`).join('\n')}
}

export type M3ColorRole = keyof M3ColorScheme

/** The Lantern action colour this palette is built around (named by the About screen). */
export const SEED_COLOR = '${hexOf(resolvePalette(spec, 'dark').action)}'

${m3Body('DARK_COLORS', 'dark')}
${m3Body('LIGHT_COLORS', 'light')}`

const m3Out = join(process.cwd(), 'packages/mobile/src/theme/m3-colors.ts')
writeFileSync(m3Out, m3File)
process.stdout.write(`wrote ${m3Out}\n`)
